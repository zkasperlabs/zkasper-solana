/// `rootCVadcopFinal`: the VADCOP final verification key the recursion
/// terminates at, hashed into the wrap's single public input.
///
/// This is not the guest key. It names the STARK verifier that checked the
/// zkasper proof, so a verifier that let a submitter choose it would accept a
/// proof recursed through a verifier the submitter set up. It is pinned here,
/// beside the circuit constants it ships with.
///
/// Four u64s big-endian, which is how `snark_publics_hash` writes both verkeys
/// — and not how it writes the publics between them. See
/// [`crate::wire::public_values`], which holds the same key the other way round.
///
/// It is **not** the value `ZiskVerifier.sol` returns from
/// `getRootCVadcopFinal()`. Upstream reissued `vadcop_final.verkey.json` on
/// 2026-08-19 and the shipped contract names the new one; the proving key
/// zkasper's provers hold is the 2026-08-17 build, and a proof only wraps under
/// the verkey its own recursion was checked against. Pinning what upstream
