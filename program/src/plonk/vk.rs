/// Width of the public window the wrap hashes.
///
/// Zisk commits guest output into a fixed 64-slot window, zero-padded, and the
/// preimage renders every slot at its full u64 width: **512** bytes on
/// v1.1.0-alpha against 256 on v1.0.0-alpha, which rendered the same slots as
/// u32. `zisk_common::snark_inputs_bytes` is the function that decides it.
///
/// The slots still carry four bytes of guest output each. Widening them did not
/// widen the output — it spread it, four bytes on and four bytes off, which is
/// what [`crate::wire::public_values`] rebuilds. So this width is part of the
/// release pin twice over: the preimage is longer *and* differently shaped.
pub const PUBLIC_VALUES_LEN: usize = 512;
