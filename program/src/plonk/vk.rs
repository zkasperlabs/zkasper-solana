//! The Zisk **v1.1.0-alpha** wrap circuit, and everything else that names a
//! Zisk release.
//!
//! Transcribed from the `PlonkVerifier.sol` the setup wrote beside the proving
//! key it belongs to — `provingKeySnark/final/PlonkVerifier.sol` — rather than
//! from a contract in a source tree, because it is the circuit in *that* key
//! that a wrap is produced under. This module is the single place in the tree
//! that pins a Zisk version: the selector and permutation commitments differ
//! between releases — v1.0.0-alpha's `Qm..Qc`/`S1..S3` are entirely different
//! points — and so do [`ROOT_C_VADCOP_FINAL`] and the width of the public
//! window. Change one of them and you must change all of them, which is why
//! they live together rather than being spread over the verifier, the wire
//! format and the fixtures.
//!
//! Eight points is the whole of the circuit difference. [`X_2`] is the same SRS
//! element, [`W1`] the same root of unity, [`K1`]/[`K2`]/[`N`] the same domain
//! and cosets, [`G2_GEN`] the same generator: the two releases wrap the same
//! statement with the same parameters and a re-run setup.
//!
//! A deployment is therefore pinned to a Zisk release by its *code*, and to a
//! zkasper guest by its *state* (see
//! [`crate::state::LightClientState::program_vk`]). Moving to a new Zisk
//! release is a program upgrade; moving to a new guest is a new light client.

